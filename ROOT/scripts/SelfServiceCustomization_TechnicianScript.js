    collectConfiguration: function() {
        let _this = $dash.gridster;
        var widgets = jQuery(_this.db).find("> ul > li.gs-w[data-widgetid]"); //No I18N
        var diminfo = {
            DefaultWidgets: {}, /* default widgets that are present in dashboard */
            ExternalWidgets: {}, /* external widgets that are present in the dashboard - only dimensional information */
            NewExternalWidgets: {}, /* external widgets newly added's dimensions */
            RemovedWidgets : {}, /* all removed widgets' dimension information of type other than external are stored here  */
            TableGraphWidgets: {}
        };

        var urlinfo = {
            NewExtUrlInfo : {}, /* newly added external widgets' title and url */
            ExtUrlInfo: {}, /* external widgets that are present in the dashboard - only urlInformation */
            RemovedExtUrlInfo : [] /* external widgets removed */
        };
        var maxi = -1;
        jQuery(_this.db).find("> ul.gridsterul > li[data-external=true]").map(function () { //No I18N
            _this.get(this, "id") && (maxi = Math.max(maxi, _this.get(this, "id"))); //No I18N
        });

        jQuery.each(widgets, function (index, widget) {
            if (_this.isExternalWidget(widget)) { /* if the widget being looked into is an external widget */
                let wid = _this.get(widget, "id"); //No I18N
                let widgetTitle = jQuery(widget).find(".widget-header .extr-titl").text();
                if(widgetTitle.trim()===translate("sdp.home.ssp.customization.common.untitledwidget")){
                    widgetTitle = "";
                }
                
                if (wid != undefined && wid != null) {
                    diminfo.ExternalWidgets[wid] = [_this.get(widget, "row"), _this.get(widget, "col"), _this.get(widget, "sizex"), _this.get(widget, "sizey")]; //No I18N

                    let type = _this.getExternalWidgetAttr(widget, "type"); //No I18N
                    let url = _this.getExternalWidgetAttr(widget, "src"); //No I18N

                    urlinfo.ExtUrlInfo[wid] = { title: widgetTitle, type : type };
                    if(type=="URL") {
                        urlinfo.ExtUrlInfo[wid].url = url;
                    }
                    else if(type=="Attach") {
                        let dummy_id=jQuery(widget).find("iframe").attr("id");
                        let fileUrl = url;
                        if(fileUrl.startsWith("/servlet/SDAjaxServlet")) {
                            fileUrl = fileUrl.slice(fileUrl.indexOf("id=")+3);
                        }
                        if(wid.startsWith("dummy") || dummy_id.indexOf("dummy")!=-1 || fileUrl.indexOf("-")!=-1) {
                            urlinfo.ExtUrlInfo[wid].id = fileUrl;
                        }
                    }
                    else if(type=="Editor") {
                        urlinfo.ExtUrlInfo[wid].content = jQuery(widget).find("iframe")[0].contentDocument.getElementsByTagName("HTML")[0].outerHTML; //No I18N
                    }
                }
            }
            else {
                /* if the widget being looked into is one of the default widgets */
                /* default widgets are added to a separate array */
                let widgetId = _this.get(widget, "id");
                let dims = ([_this.get(widget, "row"), _this.get(widget, "col"), _this.get(widget, "sizex"), _this.get(widget, "sizey")]);
                if(_this.isTableGraphWidget(widget)) {
                    diminfo.TableGraphWidgets[widgetId] = dims;
                }
                else {
                    diminfo.DefaultWidgets[widgetId] = dims;
                }
            }
        });

        /* removedWidgets array stores the list of already-persisted external widgets that have been removed in the current customization. They are stored in a separate array too, to remove permanently from the database. */
        RemovedURLInfo = [];
        jQuery.each(_this.removedWidgets.external, function (k, v) {
            RemovedURLInfo.push(v[1][0]); //No I18N
        });

        jQuery.each(parent.find("#headerbar .widget-restoremn .restore-external-widget .rmd-wgt"),function(k,v){ //No I18N
            var tempObj = {
                "title" : jQuery(v).find(".rm-wdg-name").text(), //No I18N
                "url" : jQuery(v).find(".rm-wdg-name").data("dim").url //No I18N
            }
            jQuery(v).find(".rm-wdg-name").data("dim").id = undefined; //No I18N
        });
        diminfo.RemovedWidgets = jQuery.extend(true, {}, _this.removedWidgets.default);
        try {
            for(var key in diminfo.RemovedWidgets) {
                if(typeof diminfo.RemovedWidgets[key] == 'string') {
                    diminfo.RemovedWidgets[key] = JSON.parse(diminfo.RemovedWidgets[key]);
                }
            }
        }
        catch(err) { }
        if(_this.options.collectConfigurationCallback)
        {
            _this.options.collectConfigurationCallback(_this.db,diminfo);
        }
        return {
            "diminfo" : diminfo, //No I18N
            "urlinfo" : urlinfo //No I18N
        };
    }
