        function discardConfig(message,isRemovingDraft) {
            try{
                /* rolls back the actions performed in the current customization process */             
                /* restore those default widgets to the dashboard that were previously in */
                jQuery(parent.find(".widget-restoremn ul.restore-default-widget .rmd-wgt").get().reverse()).each(function () { //No I18N
                    if (options.defaultWidgets[jQuery(this).find(".rm-wdg-name").data("dim").id] || (options.customWidgets != null && options.customWidgets[jQuery(this).find(".rm-wdg-name").data("dim").id])) { //No I18N
                        _this.restoreWidget(this);
                    }
                });                
                /* restore external widgets that were previously in. Remove the others from the list */
                jQuery(parent.find(".widget-restoremn ul.restore-external-widget .rmd-wgt").get().reverse()).each(function () { //No I18N
                    if (jQuery(this).find(".rm-wdg-name").data("dim").id) { //No I18N
                        _this.restoreWidget(this);
                    } 
                });

                if(!isRemovingDraft)
                {
                    /* remove newly added external widgets from the dashboard while discarding changes */
                    jQuery.each(jQuery(db).find("> ul.gridsterul > li[data-external=true]"), function (k, v) { //No I18N
                        if (!_this.get(v, "id")||_this.get(v,"id").search("dummy")!=-1) { //No I18N
                            removeWidgetByjQuery(v);
                        }
                        else
                        {
                            var id = _this.get(v,"id"); // No I18N
                            if(jQuery(v).attr("data-name") != options.extUrlInfo[id].title)
                            {
                                jQuery(v).attr("data-name",options.extUrlInfo[id].title);
                                jQuery(v).find(".extr-titl").text(options.extUrlInfo[id].title);
                            }
                            var url = _this.getExternalWidgetAttr(v, "src"); //No I18N
                            if(url != options.extUrlInfo[id].url)
                            {
                                _this.setExternalWidgetAttr(v, "src", options.extUrlInfo[id].url); //No I18N
                            }
                        }
                    });
                }
                else
                {
                    /* remove external widgets from the dashboard while removing draft */
                    jQuery.each(jQuery(db).find("> ul.gridsterul > li[data-external=true]"), function (k, v) { //No I18N
                        jQuery(v).remove();
                    });   
                }
                var isDashboardChangedLocal = _this.isDashboardChanged;
                parent.find(".widget-restoremn ul.restore-external-widget .rmd-wgt").remove(); //No I18N
                _this.removeWidgetTask();
                _this.removedWidgets.external = [];
                options.bgColor = dashboardPropsBackup.bgColor;
                options.numberOfColumns = dashboardPropsBackup.numberOfColumns;
                options.isWideLayout = dashboardPropsBackup.isWideLayout;
                initialise();               
                initialiseLayout();
                initialiseBGColor();
                initialiseNumberOfColumns();
                _this.enableDisableCustomization();
                if(isDashboardChangedLocal)
                {
                    _this.showAnimateAndHide("success", message.onsuccess, 1500, "easeInQuint"); //No I18N
                }
                _this.markDashboardAsUnchanged();
            }
            catch(e) {
                _this.showAnimateAndHide("failure",message.onfailure,1500,"easeInQuint"); //No I18N
            }
        }

